/* ============================================================================
   ACF GLOSSARY INDEX — behaviour for /glossary (the term-only accordion)
   ----------------------------------------------------------------------------
   Page-only progressive enhancement. Dependency-free, no build step. The page
   is generated by scripts/build-glossary-page.mjs, and the markup it emits is
   the whole contract this file relies on:

     li.gl-item#g-<id>[data-gl-item][data-gl-aliases]
       > button.gl-term[aria-expanded][aria-controls]
       + div.gl-body#gd-<id>[hidden="until-found"] > .gl-body-inner

   What this adds, in order of how often a reader will meet it:
     1. Click/tap a term: its row expands to the definition and links. Several
        rows may be open at once (a reference is compared, not read in order).
     2. Deep links: /glossary#g-<id> opens that row on load and on hashchange;
        the "Related" chips are ordinary #g-<id> anchors, so a chip hop opens
        the target row, scrolls to it, and moves focus to its button.
     3. Filter box: type to narrow the index by name, alias, or definition;
        empty groups hide; the live count reads "N of M terms"; a single match
        opens itself; Enter opens the first match; Escape clears.
     4. Find-in-page: closed rows are hidden="until-found", so the browser's own
        search can reach a definition; `beforematch` turns that reveal into a
        real open state so the chevron and aria-expanded agree with what is on
        screen. Where the attribute is unsupported it degrades to plain hidden.
     5. Expand all / Collapse all, for readers who want the whole reference.

   Motion is the grid-rows transition in reading-system.css; this file only
   sequences the attribute and class changes so the transition has a closed
   state to start from. Reduced-motion readers get instant open/close.
   JS-off readers see every definition (the .no-js rules in the stylesheet).
   ============================================================================ */
(function () {
  'use strict';

  var items = Array.prototype.slice.call(document.querySelectorAll('[data-gl-item]'));
  if (!items.length) return;

  var reduce = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
  var groups = Array.prototype.slice.call(document.querySelectorAll('[data-gl-group]'));
  var search = document.getElementById('gl-search');
  var count = document.querySelector('[data-gl-count]');
  var empty = document.querySelector('[data-gl-empty]');
  var CLOSE_SETTLE_MS = 380; // a shade past --motion-slow (320ms) so the park never clips the transition

  // Search folding: case, accents, apostrophes and punctuation are noise; a
  // hyphen is a space so "buy-borrow-die" finds "Buy, borrow, die".
  function fold(s) {
    return String(s || '')
      .toLowerCase()
      .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
      .replace(/[\u2019']/g, '')
      .replace(/[-\u2010\u2011\u2012\u2013\u2014]/g, ' ')
      .replace(/[.,;:!?()"\u201c\u201d]/g, '')
      .replace(/\s+/g, ' ')
      .trim();
  }

  var records = items.map(function (li) {
    var btn = li.querySelector('.gl-term');
    var body = li.querySelector('.gl-body');
    var nameNode = btn && btn.querySelector('.gl-term-name');
    var def = body && body.querySelector('.gl-def');
    var aliases = (li.getAttribute('data-gl-aliases') || '').split('|').join(' ');
    var name = nameNode ? nameNode.textContent : '';
    return {
      li: li, btn: btn, body: body,
      id: li.id.replace(/^g-/, ''),
      haystack: fold(name + ' ' + aliases + ' ' + (def ? def.textContent : '')),
      closeTimer: null, targetTimer: null
    };
  }).filter(function (r) { return r.btn && r.body; });

  var byId = {};
  records.forEach(function (r) { byId[r.id] = r; });
  var total = records.length;

  function isOpen(r) { return r.btn.getAttribute('aria-expanded') === 'true'; }

  function open(r, opts) {
    var instant = reduce || (opts && opts.instant);
    clearTimeout(r.closeTimer);
    if (isOpen(r) && !r.body.hasAttribute('hidden')) return;
    r.body.removeAttribute('hidden'); // the until-found attribute goes with it
    r.btn.setAttribute('aria-expanded', 'true');
    if (instant) { r.body.classList.add('is-open'); return; }
    // The closed (0fr) state must be laid out before the open one is set, or
    // there is nothing for the grid-rows transition to start from.
    void r.body.offsetHeight;
    r.body.classList.add('is-open');
  }

  function close(r, opts) {
    var instant = reduce || (opts && opts.instant);
    clearTimeout(r.closeTimer);
    if (!isOpen(r)) return;
    r.btn.setAttribute('aria-expanded', 'false');
    r.body.classList.remove('is-open');
    var park = function () {
      if (!isOpen(r)) r.body.setAttribute('hidden', 'until-found');
    };
    if (instant) { park(); return; }
    r.closeTimer = setTimeout(park, CLOSE_SETTLE_MS);
  }

  records.forEach(function (r) {
    r.btn.addEventListener('click', function () { if (isOpen(r)) close(r); else open(r); });
    // Find-in-page reached a closed definition. The browser reveals the body
    // itself (and removes `hidden`); this makes the row a real open row.
    r.body.addEventListener('beforematch', function () { open(r, { instant: true }); });
  });

  /* ---- deep links: #g-<id> on load, on hashchange, and via the related chips */
  function reveal(id, moveFocus) {
    var r = byId[id];
    if (!r) return false;
    if (search && search.value) { search.value = ''; applyFilter(''); }
    open(r);
    r.li.classList.add('is-target');
    clearTimeout(r.targetTimer);
    r.targetTimer = setTimeout(function () { r.li.classList.remove('is-target'); }, 2400);
    try {
      r.li.scrollIntoView({ block: 'start', behavior: reduce ? 'auto' : 'smooth' });
    } catch (e) {
      r.li.scrollIntoView(true);
    }
    if (moveFocus) {
      try { r.btn.focus({ preventScroll: true }); } catch (e) { r.btn.focus(); }
    }
    return true;
  }

  function fromHash() {
    var m = /^#g-([a-z0-9-]+)$/.exec(location.hash || '');
    if (m) reveal(m[1], false);
  }

  window.addEventListener('hashchange', fromHash);

  document.addEventListener('click', function (e) {
    var chip = e.target && e.target.closest && e.target.closest('a.gl-chip');
    if (!chip) return;
    // reading.js rewrites same-origin hrefs to absolute paths ("/glossary#g-x"),
    // so read the resolved parts rather than the attribute as authored.
    var m = /^#g-([a-z0-9-]+)$/.exec(chip.hash || '');
    if (!m || (chip.pathname && chip.pathname !== location.pathname)) return;
    var id = m[1];
    if (!byId[id]) return; // unknown target: let the browser do what it would have done
    e.preventDefault();
    // Keep the URL honest without re-firing hashchange for a repeat hop.
    if (window.history && typeof window.history.pushState === 'function') {
      try { window.history.pushState(null, '', '#g-' + id); } catch (err) { /* opaque origin: ignore */ }
    }
    reveal(id, true);
  });

  /* ---- filter --------------------------------------------------------------- */
  function applyFilter(raw) {
    var q = fold(raw);
    var shown = 0, last = null;
    records.forEach(function (r) {
      var hit = !q || r.haystack.indexOf(q) !== -1;
      if (hit) { r.li.classList.remove('is-hidden'); shown += 1; last = r; }
      else r.li.classList.add('is-hidden');
    });
    groups.forEach(function (g) {
      var visible = g.querySelectorAll('[data-gl-item]:not(.is-hidden)').length;
      if (visible === 0) g.classList.add('is-empty'); else g.classList.remove('is-empty');
      var c = g.querySelector('[data-gl-group-count]');
      if (c) c.textContent = String(visible);
    });
    if (count) count.textContent = q ? shown + ' of ' + total + ' terms' : total + ' terms';
    if (empty) empty.hidden = shown !== 0;
    if (q && shown === 1 && last) open(last);
  }

  function visibleRecords() {
    return records.filter(function (r) { return !r.li.classList.contains('is-hidden'); });
  }

  if (search) {
    var pending = null;
    search.addEventListener('input', function () {
      clearTimeout(pending);
      pending = setTimeout(function () { applyFilter(search.value); }, 60);
    });
    // The native clear control (the ✕ in a type=search field) fires `search`, not `input`, in some engines.
    search.addEventListener('search', function () { clearTimeout(pending); applyFilter(search.value); });
    search.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && search.value) {
        e.preventDefault();
        search.value = '';
        applyFilter('');
      } else if (e.key === 'Enter') {
        e.preventDefault();
        var first = visibleRecords()[0];
        if (first) { open(first); try { first.btn.focus({ preventScroll: true }); } catch (err) { first.btn.focus(); } first.li.scrollIntoView({ block: 'nearest' }); }
      }
    });
  }

  /* ---- expand all / collapse all (visible rows only) ----------------------- */
  var expandAll = document.querySelector('[data-gl-expand]');
  var collapseAll = document.querySelector('[data-gl-collapse]');
  if (expandAll) expandAll.addEventListener('click', function () {
    visibleRecords().forEach(function (r) { open(r, { instant: true }); });
  });
  if (collapseAll) collapseAll.addEventListener('click', function () {
    records.forEach(function (r) { close(r, { instant: true }); });
  });

  // The browser's own hash jump already happened (this script is deferred), so
  // the row is in view; opening it is the part that was missing.
  fromHash();
})();
